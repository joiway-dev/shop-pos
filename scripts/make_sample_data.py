def _styled(ws, headers: list[str], widths: dict[int, int]) -> None:
    bold, fill = Font(bold=True), PatternFill("solid", fgColor="FBE7D9")
    for i, _ in enumerate(headers, start=1):
        cell = ws.cell(row=1, column=i)
        cell.font, cell.fill = bold, fill
        ws.column_dimensions[cell.column_letter].width = widths.get(i, 14)
    ws.freeze_panes = "A2"


def product_file() -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "สินค้า"
    ws.append(pi.HEADERS)
    for n, (name, cat, unit, price, min_stock, aliases, extra, default, barcode) in enumerate(PRODUCTS, start=1):
        row = {h: "" for h in pi.HEADERS}
        row.update({pi.COL_SKU: f"P{n:05d}", pi.COL_BARCODE: barcode, pi.COL_NAME: name, pi.COL_CATEGORY: cat,
                    pi.COL_BASE_UNIT: unit, pi.COL_BASE_PRICE: price, pi.COL_DEFAULT_UNIT: default,
                    pi.COL_MIN_STOCK: min_stock, pi.COL_ALIASES: aliases})
        for i, (u, f, p) in enumerate(extra, start=2):
            name_c, factor_c, price_c, _ = pi.unit_columns(i)
            row.update({name_c: u, factor_c: f, price_c: p})
        ws.append([row[h] for h in pi.HEADERS])
    for r in range(2, ws.max_row + 1):
        for c in (1, 2):
            ws.cell(row=r, column=c).number_format = "@"
    _styled(ws, pi.HEADERS, {2: 16, 3: 36, 4: 18, 10: 34})
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def opening_file() -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "ยอดยกมา"
    ws.append(oi.HEADERS)
    for n, (name, _cat, unit, price, min_stock, *_rest) in enumerate(PRODUCTS, start=1):
        sku = f"P{n:05d}"
        minimum = int(min_stock)
        qty = max(1, minimum // 2) if sku in LOW else minimum * 3 + (n * 7) % 20
        pct = Decimal("0.78") + Decimal(n % 5) * Decimal("0.02")  # 78%-86% of the price
        cost = (Decimal(price) * pct).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
        ws.append([sku, name, unit, str(qty), str(cost)])
    for r in range(2, ws.max_row + 1):
        ws.cell(row=r, column=1).number_format = "@"
    _styled(ws, oi.HEADERS, {2: 40, 4: 22, 5: 24})
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def main() -> None:
    OUT.mkdir(exist_ok=True)
    (OUT / "1_สินค้าตัวอย่าง.xlsx").write_bytes(product_file())
    (OUT / "2_ยอดยกมาตัวอย่าง.xlsx").write_bytes(opening_file())
    (OUT / "3_ข้อความสั่งซื้อจากLINE.txt").write_text(LINE_ORDERS, encoding="utf-8-sig")
    print(f"สร้างไฟล์ตัวอย่างใน {OUT}")


if __name__ == "__main__":
    main()
